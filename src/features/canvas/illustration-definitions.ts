/**
 * 插画素材库（纯数据，不导出组件）。
 *
 * 与贴纸的差别：插画是**画布级对象**（挂在画布坐标上，不依附某个主题），
 * 尺寸更大（默认 120，可缩放）——对应 XMind 插入菜单里的「插画」。
 *
 * 图元格式与贴纸完全一致（`{ d, fill, stroke?, strokeWidth? }`），
 * 所以 Canvas(PNG) / SVG 两端可以直接复用同一套绘制代码；画布层（Canvas 2D）与导出端同源，
 * 所以**不需要 DOM 元素**也能在屏幕上显示。
 *
 * ⚠️ **不要用接近画布底色的填充**：第一版把火箭机身与云朵写成 `#f8fafc`，
 * 在浅色画布（默认 251,251,253）上几乎完全看不见（真引擎截图发现）。
 * 浅色造型一律配深一点的描边，或直接用中灰。
 *
 * 本文件由 dev 脚本生成（圆形/矩形的 d 命令由脚本计算，避免手写弧命令画歪。
 */

